"""Ловим отказы и ответы «как ассистент», чтобы роутер повторил запрос другой моделью."""

import re

# Фразы, которые живая Ника никогда бы не написала
_PATTERNS = [
    r"\bкак (?:языковая модель|ии|искусственный интеллект|ассистент)\b",
    r"\bя (?:всего лишь )?(?:языковая модель|ии-ассистент|виртуальный ассистент|ассистент)\b",
    r"\bне могу (?:продолжить|помочь с этим|выполнить (?:эту|этот|ваш) (?:просьбу|запрос))\b",
    r"\b(?:это|данный) (?:запрос|контент) (?:нарушает|противоречит)\b",
    r"\bчем (?:я )?могу (?:вам )?помочь\b",
    r"\bI (?:can't|cannot|won't) (?:help|continue|assist|provide|engage)\b",
    r"\bas an AI\b",
    r"\bI'm sorry, but\b",
    # Модель вместо ответа пересказывает служебные подсказки
    r"\bне выдумывай\b",
    r"\bподсказк\w* для ники\b",
    r"\bслужебн\w+ подсказк",
    r"\(его часовой пояс\)",
    r"\bответь (?:ему )?(?:как ника|на заданн)",
]
_REGEX = re.compile("|".join(_PATTERNS), re.IGNORECASE)


def looks_like_refusal(text: str) -> bool:
    """True, если ответ похож на отказ или на речь ассистента."""
    if not text.strip():
        return True
    return bool(_REGEX.search(text))
